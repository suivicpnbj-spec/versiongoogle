export function coordsToLatLng(x: number, y: number): { lat: number; lng: number } {
  const lat = 9.372 - (y / 700) * 0.068;
  const lng = 2.592 + (x / 1000) * 0.078;
  return {
    lat: Number(lat.toFixed(5)),
    lng: Number(lng.toFixed(5)),
  };
}

export function latLngToSvg(lat: number, lng: number): { x: number; y: number } {
  const x = Math.max(40, Math.min(960, Math.round(((lng - 2.592) / 0.078) * 1000)));
  const y = Math.max(40, Math.min(660, Math.round(((9.372 - lat) / 0.068) * 700)));
  return { x, y };
}

export function generateDemoThreeWordCode(x: number, y: number): string {
  const w1 = DEMO_WORDS[Math.abs(Math.floor(x * 7 + y)) % DEMO_WORDS.length];
  const w2 = DEMO_WORDS[Math.abs(Math.floor(y * 5 + x * 3)) % DEMO_WORDS.length];
  const w3 = DEMO_WORDS[Math.abs(Math.floor(x + y * 11 + 5)) % DEMO_WORDS.length];
  return `///${w1}.${w2}.${w3}`;
}

export function findNearestNeighborhood(x: number, y: number): ParakouNeighborhoodNode {
  let best = PARAKOU_NEIGHBORHOODS[0];
  let minDist = Infinity;
  for (const node of PARAKOU_NEIGHBORHOODS) {
    const dx = node.coordinates.x - x;
    const dy = node.coordinates.y - y;
    const d = dx * dx + dy * dy;
    if (d < minDist) {
      minDist = d;
      best = node;
    }
  }
  return best;
}

export function estimateDistanceKm(a: Coordinates, b: Coordinates): number {
  const dx = (a.x - b.x) / 145;
  const dy = (a.y - b.y) / 145;
  return Math.max(0.3, Number(Math.hypot(dx, dy).toFixed(1)));
}

